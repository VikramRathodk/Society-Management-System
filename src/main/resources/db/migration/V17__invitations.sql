-- Invitations: bringing a person into a society with a role, following the role hierarchy.
-- Only a SHA-256 hash of the link's token is stored, so the database alone can't be used to accept one.
-- An invitation goes with its society, role or flat; who sent or accepted one is kept as history.
CREATE TABLE invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES role(id) ON DELETE CASCADE,
    flat_id BIGINT REFERENCES flat(id) ON DELETE CASCADE,
    resident_type VARCHAR(20) CHECK (resident_type IN ('OWNER','FAMILY','TENANT')),
    phone VARCHAR(15) NOT NULL,
    name VARCHAR(255) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    -- AWAITING_APPROVAL / REJECTED are for invitations sent by residents (approved by the committee).
    status VARCHAR(20) NOT NULL CHECK (status IN
        ('PENDING','AWAITING_APPROVAL','ACCEPTED','DECLINED','REJECTED','REVOKED','EXPIRED')),
    invited_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    -- When it was accepted, declined, revoked or expired, and by whom where that's a person.
    closed_at TIMESTAMP,
    closed_by BIGINT REFERENCES users(id),
    accepted_user_id BIGINT REFERENCES users(id)
);

CREATE INDEX idx_invitation_society_created ON invitation (society_id, created_at DESC);
CREATE INDEX idx_invitation_phone_status ON invitation (phone, status);

-- At most one open invitation per person, society, role and flat.
CREATE UNIQUE INDEX uq_invitation_open ON invitation (society_id, role_id, phone, COALESCE(flat_id, 0))
    WHERE status IN ('PENDING', 'AWAITING_APPROVAL');

INSERT INTO permission (module, feature, subfeature, action, code, description) VALUES
