-- COMMITTEE invites residents; SECRETARY and ADMIN inherit and can invite higher roles by rank.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id FROM role r JOIN permission p ON p.code IN ('USER.INVITE.CREATE', 'USER.INVITE.VIEW')
WHERE r.code = 'COMMITTEE';
