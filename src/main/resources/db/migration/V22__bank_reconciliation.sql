-- Bank reconciliation (finance V1.1): bank statements per bank ledger, their imported lines, and which
-- book lines each bank line cleared. Reconciliation never changes a voucher; it only records matches.

-- How a bank's CSV export reads, saved per bank account on the first upload. Columns are 1-based.
CREATE TABLE finance_statement_mapping (
    account_id BIGINT PRIMARY KEY REFERENCES finance_bank_account(account_id) ON DELETE CASCADE,
    delimiter VARCHAR(1) NOT NULL DEFAULT ',' CHECK (delimiter IN (',', ';', E'\t', '|')),
    -- The line holding the column names; data starts on the next line.
    header_row INT NOT NULL CHECK (header_row BETWEEN 1 AND 100),
    date_column INT NOT NULL CHECK (date_column > 0),
    date_format VARCHAR(20) NOT NULL,
    description_column INT NOT NULL CHECK (description_column > 0),
    reference_column INT CHECK (reference_column > 0),
    -- DEBIT_CREDIT: separate withdrawal and deposit columns. AMOUNT_TYPE: one amount and a Dr/Cr column.
    -- SIGNED: one amount, negative (or in brackets) for a withdrawal.
    amount_style VARCHAR(20) NOT NULL CHECK (amount_style IN ('DEBIT_CREDIT', 'AMOUNT_TYPE', 'SIGNED')),
    debit_column INT CHECK (debit_column > 0),
    credit_column INT CHECK (credit_column > 0),
    amount_column INT CHECK (amount_column > 0),
    type_column INT CHECK (type_column > 0),
    balance_column INT CHECK (balance_column > 0),
    updated_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    CHECK (amount_style <> 'DEBIT_CREDIT' OR (debit_column IS NOT NULL AND credit_column IS NOT NULL)),
    CHECK (amount_style <> 'AMOUNT_TYPE' OR (amount_column IS NOT NULL AND type_column IS NOT NULL)),
    CHECK (amount_style <> 'SIGNED' OR amount_column IS NOT NULL)
);

-- One bank statement period of one bank ledger. Balances are as the bank shows them: positive is money
-- in the account, negative is overdrawn. Periods of an account follow each other; one is open at a time.
CREATE TABLE finance_bank_statement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    account_id BIGINT NOT NULL REFERENCES finance_bank_account(account_id),
    period_from DATE NOT NULL,
    period_to DATE NOT NULL,
    opening_balance NUMERIC(14,2) NOT NULL,
    closing_balance NUMERIC(14,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'COMPLETED')),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TIMESTAMP,
    completed_at TIMESTAMP,
    completed_by BIGINT REFERENCES users(id),
    reopened_at TIMESTAMP,
    reopened_by BIGINT REFERENCES users(id),
    reopen_reason VARCHAR(500),
    -- Snapshot of the bank reconciliation statement, taken when it is completed.
    book_balance NUMERIC(14,2),
    uncleared_receipts NUMERIC(14,2),
    uncleared_payments NUMERIC(14,2),
    CHECK (period_to >= period_from),
    CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_finance_bank_statement_period ON finance_bank_statement(account_id, period_from);
CREATE UNIQUE INDEX uq_finance_bank_statement_open ON finance_bank_statement(account_id) WHERE status = 'OPEN';
CREATE INDEX idx_finance_bank_statement_society ON finance_bank_statement(society_id);

-- Each CSV uploaded into a statement. The file itself is kept in the shared storage.
CREATE TABLE finance_bank_statement_import (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL REFERENCES finance_bank_statement(id) ON DELETE CASCADE,
    filename VARCHAR(255),
    storage_key VARCHAR(100) NOT NULL,
    size_bytes INT NOT NULL CHECK (size_bytes > 0),
    rows_imported INT NOT NULL CHECK (rows_imported >= 0),
    rows_duplicate INT NOT NULL CHECK (rows_duplicate >= 0),
    rows_ignored INT NOT NULL CHECK (rows_ignored >= 0),
    imported_at TIMESTAMP NOT NULL DEFAULT now(),
    imported_by BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX idx_finance_bank_statement_import_statement ON finance_bank_statement_import(statement_id);

-- One transaction line of a bank statement. Exactly one of debit (money out) and credit (money in) is set.
CREATE TABLE finance_bank_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL REFERENCES finance_bank_statement(id) ON DELETE CASCADE,
    import_id BIGINT NOT NULL REFERENCES finance_bank_statement_import(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES finance_bank_account(account_id),
    -- Order within the statement, as the bank lists it (oldest first).
    line_no INT NOT NULL,
    txn_date DATE NOT NULL,
    description VARCHAR(500) NOT NULL,
    reference VARCHAR(100),
    debit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    balance NUMERIC(14,2),
    -- Same bank transaction, same fingerprint: imported once per bank account.
    fingerprint VARCHAR(64) NOT NULL,
    state VARCHAR(20) NOT NULL DEFAULT 'UNMATCHED' CHECK (state IN ('UNMATCHED', 'MATCHED', 'EXCLUDED')),
    exclude_reason VARCHAR(500),
    -- A voucher recorded from this line (bank charges, interest, a forgotten receipt).
    voucher_id BIGINT REFERENCES finance_voucher(id),
    CHECK ((debit > 0) <> (credit > 0)),
    CHECK ((state = 'EXCLUDED') = (exclude_reason IS NOT NULL))
);

CREATE UNIQUE INDEX uq_finance_bank_line_fingerprint ON finance_bank_line(account_id, fingerprint);
CREATE UNIQUE INDEX uq_finance_bank_line_no ON finance_bank_line(statement_id, line_no);
CREATE INDEX idx_finance_bank_line_import ON finance_bank_line(import_id);

-- A book line (on the statement's bank ledger) cleared against a bank line. Several book lines may
-- clear one bank line; a book line clears once. A voided entry and its reversal that never reached the
-- bank clear each other: no bank line, pair_line_id set.
CREATE TABLE finance_bank_match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL REFERENCES finance_bank_statement(id) ON DELETE CASCADE,
    bank_line_id BIGINT REFERENCES finance_bank_line(id) ON DELETE CASCADE,
    finance_line_id BIGINT NOT NULL UNIQUE REFERENCES finance_line(id),
    pair_line_id BIGINT REFERENCES finance_line(id),
    auto BOOLEAN NOT NULL DEFAULT false,
    matched_at TIMESTAMP NOT NULL DEFAULT now(),
    matched_by BIGINT NOT NULL REFERENCES users(id),
    CHECK ((bank_line_id IS NULL) <> (pair_line_id IS NULL))
);

CREATE INDEX idx_finance_bank_match_statement ON finance_bank_match(statement_id);
CREATE INDEX idx_finance_bank_match_bank_line ON finance_bank_match(bank_line_id);

-- A match's book line posts to the statement's bank ledger.
CREATE FUNCTION finance_bank_match_check() RETURNS trigger AS $$
DECLARE
    statement_account BIGINT;
    line_account BIGINT;
BEGIN
    SELECT account_id INTO statement_account FROM finance_bank_statement WHERE id = NEW.statement_id;
    SELECT account_id INTO line_account FROM finance_line WHERE id = NEW.finance_line_id;
    IF line_account <> statement_account THEN
        RAISE EXCEPTION 'finance_bank_match: book line % is not on the statement''s bank account', NEW.finance_line_id;
    END IF;
    IF NEW.bank_line_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM finance_bank_line WHERE id = NEW.bank_line_id AND statement_id = NEW.statement_id
    ) THEN
        RAISE EXCEPTION 'finance_bank_match: bank line % is not on statement %', NEW.bank_line_id, NEW.statement_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_finance_bank_match_check BEFORE INSERT OR UPDATE ON finance_bank_match
    FOR EACH ROW EXECUTE FUNCTION finance_bank_match_check();

-- The book lines matched to a bank line add up to it (money in the bank is a debit of the bank ledger).
-- Checked at commit, once all the matches of a bank line are written.
CREATE FUNCTION finance_bank_match_total_check() RETURNS trigger AS $$
DECLARE
    lid BIGINT := COALESCE(NEW.bank_line_id, OLD.bank_line_id);
    bank_net NUMERIC;
    book_net NUMERIC;
    match_count INT;
BEGIN
    IF lid IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT credit - debit INTO bank_net FROM finance_bank_line WHERE id = lid;
    IF bank_net IS NULL THEN
        RETURN NULL; -- the bank line itself was removed
    END IF;
    SELECT COUNT(*), COALESCE(SUM(fl.debit - fl.credit), 0) INTO match_count, book_net
        FROM finance_bank_match m JOIN finance_line fl ON fl.id = m.finance_line_id
        WHERE m.bank_line_id = lid;
    IF match_count > 0 AND book_net <> bank_net THEN
        RAISE EXCEPTION 'finance bank line % does not match its book lines: bank % <> books %', lid, bank_net, book_net;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_finance_bank_match_total AFTER INSERT OR UPDATE OR DELETE ON finance_bank_match
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION finance_bank_match_total_check();

