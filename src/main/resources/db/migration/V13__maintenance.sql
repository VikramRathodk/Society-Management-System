-- Maintenance billing (module 14, M7a). A society configures what it charges (settings + charge heads),
-- then issues a billing cycle: one bill per flat, with the charges copied into bill lines so later edits to
-- the configuration never change an issued bill. Payments come in M7b.
--
-- Configuration rows cascade with their society; bills and cycles do not, so a society with billing
-- history cannot be deleted (same rule as visitors, notices and complaints).

-- Needed only by per-sq-ft charge heads.
ALTER TABLE flat
    ADD COLUMN area_sqft NUMERIC(8,2) CHECK (area_sqft > 0);

-- One row per society; absent means the defaults below.
CREATE TABLE maintenance_settings (
    society_id BIGINT PRIMARY KEY REFERENCES society(id) ON DELETE CASCADE,
    -- Length of the suggested next billing period; any cycle may still use its own dates.
    billing_frequency VARCHAR(20) NOT NULL DEFAULT 'MONTHLY'
        CHECK (billing_frequency IN ('MONTHLY','QUARTERLY','HALF_YEARLY','YEARLY')),
    -- Suggested due date = period start + due_days.
    due_days INT NOT NULL DEFAULT 15 CHECK (due_days BETWEEN 0 AND 365),
    -- Round each bill line to whole rupees (half up) instead of paise.
    round_to_rupee BOOLEAN NOT NULL DEFAULT true,
    updated_at TIMESTAMP,
    updated_by BIGINT REFERENCES users(id)
);

-- What a society charges every flat each cycle, e.g. Maintenance, Sinking fund, Parking.
CREATE TABLE maintenance_charge_head (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    -- FIXED: amount per flat. PER_SQFT: amount is the rate per sq ft of the flat's area.
    calc_type VARCHAR(20) NOT NULL CHECK (calc_type IN ('FIXED','PER_SQFT')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    is_active BOOLEAN NOT NULL DEFAULT true,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (society_id, name)
);

CREATE TABLE maintenance_cycle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED','CANCELLED')),
    issued_at TIMESTAMP NOT NULL DEFAULT now(),
    issued_by BIGINT NOT NULL REFERENCES users(id),
    cancelled_at TIMESTAMP,
    cancelled_by BIGINT REFERENCES users(id),
    cancel_reason TEXT,
    CHECK (period_end >= period_start),
    CHECK (due_date >= period_start)
);

-- A period is billed once; a cancelled cycle frees it. Overlapping periods are refused by the service,
-- which locks the society row while issuing.
CREATE UNIQUE INDEX uq_maintenance_cycle_period ON maintenance_cycle(society_id, period_start)
    WHERE status = 'ISSUED';
CREATE INDEX idx_maintenance_cycle_society ON maintenance_cycle(society_id, period_start DESC);

CREATE TABLE maintenance_bill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id BIGINT NOT NULL REFERENCES maintenance_cycle(id),
    society_id BIGINT NOT NULL REFERENCES society(id),
    flat_id BIGINT NOT NULL REFERENCES flat(id),
    -- e.g. 202611-0007: period start month, then the flat's position in the cycle.
    bill_number VARCHAR(30) NOT NULL,
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    -- PARTIAL and PAID are set by payments (M7b).
    status VARCHAR(20) NOT NULL DEFAULT 'UNPAID'
        CHECK (status IN ('UNPAID','PARTIAL','PAID','WAIVED','CANCELLED')),
    -- Why it was waived or cancelled, by whom and when.
    status_reason TEXT,
    status_changed_at TIMESTAMP,
    status_changed_by BIGINT REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (cycle_id, flat_id),
    UNIQUE (cycle_id, bill_number)
);

-- A resident's view: their flat's bills, newest first.
CREATE INDEX idx_maintenance_bill_flat ON maintenance_bill(flat_id, created_at DESC);
CREATE INDEX idx_maintenance_bill_society_status ON maintenance_bill(society_id, status);

-- The charges as they were when the bill was issued.
CREATE TABLE maintenance_bill_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES maintenance_bill(id) ON DELETE CASCADE,
    head_name VARCHAR(100) NOT NULL,
    calc_type VARCHAR(20) NOT NULL,
    rate NUMERIC(12,2) NOT NULL,
    -- 1 for FIXED, the flat's area for PER_SQFT.
    quantity NUMERIC(10,2) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_maintenance_bill_line_bill ON maintenance_bill_line(bill_id);

