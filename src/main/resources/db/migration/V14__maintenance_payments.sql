-- Maintenance payments, late fees and opening balances (module 14, M7b).
--
-- Payments are offline (cash, cheque, UPI, bank transfer) and are recorded by the society. Each payment
-- is split across the flat's bills (allocations); a bill's amount_paid is the sum of its allocations from
-- payments that are not void, kept up to date by the service under a lock on the society row.

-- Late payment rule, applied as "Late charges" lines on the next cycle's bills.
--   NONE: no late charges.
--   FIXED: late_fee_value rupees, once per overdue bill.
--   SIMPLE_INTEREST: late_fee_value % a year on the bill's outstanding amount, for the days since its due
--   date (or since it was last charged).
-- A bill is overdue once grace_days have passed after its due date.
ALTER TABLE maintenance_settings
    ADD COLUMN late_fee_type VARCHAR(20) NOT NULL DEFAULT 'NONE'
        CHECK (late_fee_type IN ('NONE','FIXED','SIMPLE_INTEREST')),
    ADD COLUMN late_fee_value NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (late_fee_value >= 0),
    ADD COLUMN grace_days INT NOT NULL DEFAULT 0 CHECK (grace_days BETWEEN 0 AND 365);

-- OPENING_BALANCE: a one-off cycle holding dues from before the society used the app, one bill per flat
-- that owed something. At most one is issued per society, and it never blocks a regular period.
ALTER TABLE maintenance_cycle
    ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'REGULAR' CHECK (kind IN ('REGULAR','OPENING_BALANCE'));

DROP INDEX uq_maintenance_cycle_period;
CREATE UNIQUE INDEX uq_maintenance_cycle_period ON maintenance_cycle(society_id, period_start)
    WHERE status = 'ISSUED' AND kind = 'REGULAR';
CREATE UNIQUE INDEX uq_maintenance_cycle_opening ON maintenance_cycle(society_id)
    WHERE status = 'ISSUED' AND kind = 'OPENING_BALANCE';

ALTER TABLE maintenance_bill
    ADD COLUMN amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    ADD CONSTRAINT chk_maintenance_bill_paid CHECK (amount_paid <= total);

-- Lines that are not charge heads: late charges (pointing at the overdue bill and the day they were
-- charged up to) and opening balances. calc_type gains LATE_FEE and OPENING_BALANCE for them.
ALTER TABLE maintenance_bill_line
    ADD COLUMN note VARCHAR(200),
    ADD COLUMN source_bill_id BIGINT REFERENCES maintenance_bill(id),
    ADD COLUMN charged_through DATE;

CREATE INDEX idx_maintenance_bill_line_source ON maintenance_bill_line(source_bill_id)
    WHERE source_bill_id IS NOT NULL;

CREATE TABLE maintenance_payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    flat_id BIGINT NOT NULL REFERENCES flat(id),
    -- R-000001, R-000002 … per society, in the order payments were recorded.
    receipt_number VARCHAR(30) NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL,
    method VARCHAR(20) NOT NULL CHECK (method IN ('CASH','CHEQUE','UPI','BANK_TRANSFER')),
    -- Cheque number, UPI transaction id, bank reference …
    reference VARCHAR(100),
    note TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'RECORDED' CHECK (status IN ('RECORDED','VOID')),
    recorded_at TIMESTAMP NOT NULL DEFAULT now(),
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    voided_at TIMESTAMP,
    voided_by BIGINT REFERENCES users(id),
    void_reason TEXT,
    UNIQUE (society_id, receipt_number)
);

CREATE INDEX idx_maintenance_payment_society ON maintenance_payment(society_id, paid_on DESC);
CREATE INDEX idx_maintenance_payment_flat ON maintenance_payment(flat_id, paid_on DESC);

-- How much of a payment went to which bill. Kept when the payment is voided, as history.
CREATE TABLE maintenance_payment_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES maintenance_payment(id),
    bill_id BIGINT NOT NULL REFERENCES maintenance_bill(id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    UNIQUE (payment_id, bill_id)
);

CREATE INDEX idx_maintenance_payment_allocation_bill ON maintenance_payment_allocation(bill_id);
