-- Finance & accounting (module 15). Double-entry books per society: a chart of accounts (groups and
-- ledgers), bank account details, vouchers made of debit/credit lines, attachments, and an insert-only
-- audit log. Design: docs/modules/finance.md.
--
-- Nothing here cascades from the society: a society whose books exist keeps them (and cannot be
-- deleted), the same rule as maintenance bills.

-- The chart of accounts. A group holds other accounts and is never posted to; a ledger is posted to.
-- Each type has one root group (parent_id null). A child always has its parent's type (checked by the
-- service when creating or moving).
CREATE TABLE finance_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    code VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('ASSET','LIABILITY','FUND','INCOME','EXPENSE')),
    parent_id BIGINT REFERENCES finance_account(id),
    is_group BOOLEAN NOT NULL,
    -- Accounts that postings rely on (CASH, MEMBER_DUES, ...); they can't be deleted, retyped or deactivated.
    system_key VARCHAR(40),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP,
    CHECK (parent_id IS NOT NULL OR is_group),
    CHECK (parent_id IS NULL OR parent_id <> id),
    UNIQUE (society_id, code)
);

CREATE UNIQUE INDEX uq_finance_account_name ON finance_account(society_id, lower(name));
CREATE UNIQUE INDEX uq_finance_account_system ON finance_account(society_id, system_key) WHERE system_key IS NOT NULL;
CREATE UNIQUE INDEX uq_finance_account_root ON finance_account(society_id, type) WHERE parent_id IS NULL;
CREATE INDEX idx_finance_account_parent ON finance_account(parent_id);

-- Details of a bank ledger. Only the last 4 digits of the account number are kept: nothing secret.
CREATE TABLE finance_bank_account (
    account_id BIGINT PRIMARY KEY REFERENCES finance_account(id) ON DELETE CASCADE,
    bank_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(20) NOT NULL CHECK (account_type IN ('SAVINGS','CURRENT')),
    last4 VARCHAR(4) CHECK (last4 ~ '^[0-9]{4}$'),
    ifsc VARCHAR(11) CHECK (ifsc ~ '^[A-Z]{4}0[A-Z0-9]{6}$')
);

-- One row per society once its books are started.
CREATE TABLE finance_books (
    society_id BIGINT PRIMARY KEY REFERENCES society(id),
    start_date DATE NOT NULL,
    -- No voucher may be dated, approved or voided on or before this day.
    locked_until DATE,
    -- Where maintenance payments go, per method, and the account expenses are paid from by default.
    cash_deposit_account_id BIGINT REFERENCES finance_account(id),
    cheque_deposit_account_id BIGINT REFERENCES finance_account(id),
    upi_deposit_account_id BIGINT REFERENCES finance_account(id),
    transfer_deposit_account_id BIGINT REFERENCES finance_account(id),
    default_paying_account_id BIGINT REFERENCES finance_account(id),
    started_at TIMESTAMP NOT NULL DEFAULT now(),
    started_by BIGINT NOT NULL REFERENCES users(id),
    CHECK (locked_until IS NULL OR locked_until >= start_date)
);

-- Which ledger a maintenance charge head credits when bills are issued (default: Maintenance charges).
CREATE TABLE finance_charge_head_account (
    charge_head_id BIGINT PRIMARY KEY REFERENCES maintenance_charge_head(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES finance_account(id)
);

CREATE TABLE finance_voucher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    type VARCHAR(20) NOT NULL CHECK (type IN ('RECEIPT','PAYMENT','CONTRA','JOURNAL','OPENING','SYSTEM')),
    -- e.g. 2026-27; numbers restart every financial year, per type.
    financial_year VARCHAR(9) NOT NULL,
    seq INT NOT NULL CHECK (seq > 0),
    number VARCHAR(30) NOT NULL,
    voucher_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_APPROVAL','POSTED','REJECTED','VOID')),
    narration VARCHAR(500),
    payee VARCHAR(200),
    reference VARCHAR(100),
    -- Total of the debit lines.
    amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    -- Automatic postings: what caused them. One posting per source event.
    source_type VARCHAR(30),
    source_id BIGINT,
    source_event VARCHAR(30),
    -- A reversal points at the voucher it cancels.
    reverses_voucher_id BIGINT REFERENCES finance_voucher(id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TIMESTAMP,
    decided_at TIMESTAMP,
    decided_by BIGINT REFERENCES users(id),
    voided_at TIMESTAMP,
    voided_by BIGINT REFERENCES users(id),
    -- Why it was rejected or voided.
    reason VARCHAR(500),
    UNIQUE (society_id, type, financial_year, seq),
    CHECK ((source_type IS NULL) = (source_id IS NULL) AND (source_type IS NULL) = (source_event IS NULL))
);

CREATE UNIQUE INDEX uq_finance_voucher_number ON finance_voucher(society_id, number);
CREATE UNIQUE INDEX uq_finance_voucher_source ON finance_voucher(society_id, source_type, source_id, source_event)
    WHERE source_type IS NOT NULL;
CREATE UNIQUE INDEX uq_finance_voucher_reversal ON finance_voucher(reverses_voucher_id) WHERE reverses_voucher_id IS NOT NULL;
CREATE INDEX idx_finance_voucher_society_date ON finance_voucher(society_id, voucher_date);
CREATE INDEX idx_finance_voucher_status ON finance_voucher(society_id, status);

CREATE TABLE finance_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL REFERENCES finance_voucher(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES finance_account(id),
    -- Only on the per-flat sub-ledgers (MEMBER_DUES, MEMBER_ADVANCE), and always there.
    flat_id BIGINT REFERENCES flat(id),
    debit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    line_order INT NOT NULL DEFAULT 0,
    CHECK ((debit > 0) <> (credit > 0))
);

CREATE INDEX idx_finance_line_voucher ON finance_line(voucher_id);
CREATE INDEX idx_finance_line_account ON finance_line(account_id);
CREATE INDEX idx_finance_line_flat ON finance_line(account_id, flat_id) WHERE flat_id IS NOT NULL;

-- A line must post to a ledger (not a group) of the voucher's own society, with a flat exactly when the
-- ledger is a per-flat sub-ledger.
CREATE FUNCTION finance_line_check() RETURNS trigger AS $$
DECLARE
    acc finance_account%ROWTYPE;
    voucher_society BIGINT;
BEGIN
    SELECT * INTO acc FROM finance_account WHERE id = NEW.account_id;
    SELECT society_id INTO voucher_society FROM finance_voucher WHERE id = NEW.voucher_id;
    IF acc.society_id <> voucher_society THEN
        RAISE EXCEPTION 'finance_line: account % belongs to another society', NEW.account_id;
    END IF;
    IF acc.is_group THEN
        RAISE EXCEPTION 'finance_line: account % is a group and cannot be posted to', NEW.account_id;
    END IF;
    IF COALESCE(acc.system_key IN ('MEMBER_DUES','MEMBER_ADVANCE'), false) <> (NEW.flat_id IS NOT NULL) THEN
        RAISE EXCEPTION 'finance_line: flat is required on member sub-ledgers and allowed nowhere else';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_finance_line_check BEFORE INSERT OR UPDATE ON finance_line
    FOR EACH ROW EXECUTE FUNCTION finance_line_check();

-- Every voucher balances (debits = credits). Checked at commit, once all its lines are written.
CREATE FUNCTION finance_voucher_balance_check() RETURNS trigger AS $$
DECLARE
    vid BIGINT := COALESCE(NEW.voucher_id, OLD.voucher_id);
    total_debit NUMERIC;
    total_credit NUMERIC;
BEGIN
    SELECT COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0) INTO total_debit, total_credit
        FROM finance_line WHERE voucher_id = vid;
    IF total_debit <> total_credit THEN
        RAISE EXCEPTION 'finance voucher % does not balance: debit % <> credit %', vid, total_debit, total_credit;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_finance_voucher_balance AFTER INSERT OR UPDATE OR DELETE ON finance_line
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION finance_voucher_balance_check();

-- Supporting documents (invoice, receipt, approval, bank proof) of a voucher. The bytes live in the
-- shared photo storage under storage_key.
CREATE TABLE finance_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL REFERENCES finance_voucher(id) ON DELETE CASCADE,
    document_type VARCHAR(20) NOT NULL CHECK (document_type IN ('INVOICE','RECEIPT','APPROVAL','BANK_PROOF','OTHER')),
    storage_key VARCHAR(100) NOT NULL,
    filename VARCHAR(255),
    content_type VARCHAR(100) NOT NULL,
    size_bytes INT NOT NULL CHECK (size_bytes > 0),
    uploaded_at TIMESTAMP NOT NULL DEFAULT now(),
    uploaded_by BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX idx_finance_document_voucher ON finance_document(voucher_id);

-- Who changed what in the books, and why. Written in the same transaction as the change.
CREATE TABLE finance_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    entity_type VARCHAR(20) NOT NULL,
    entity_id BIGINT,
    action VARCHAR(20) NOT NULL,
    -- JSON objects of the changed fields; never secrets.
    old_values TEXT,
    new_values TEXT,
    reason VARCHAR(500),
    performed_by BIGINT NOT NULL REFERENCES users(id),
    performed_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_finance_audit_society ON finance_audit_log(society_id, performed_at DESC);
CREATE INDEX idx_finance_audit_entity ON finance_audit_log(entity_type, entity_id);

-- Insert-only: audit rows can't be changed or removed, by the app or by hand.
CREATE FUNCTION finance_audit_log_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'finance_audit_log is insert-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_finance_audit_log_immutable BEFORE UPDATE OR DELETE ON finance_audit_log
    FOR EACH ROW EXECUTE FUNCTION finance_audit_log_immutable();

