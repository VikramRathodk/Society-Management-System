-- Visitor management (M3).

-- Uploaded photos, kept in the database for now. Callers only ever see an opaque key (PhotoStorage),
-- so moving to object storage (S3 etc.) later means a new PhotoStorage + copying rows, no API change.
CREATE TABLE stored_photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(100) NOT NULL,
    size_bytes INTEGER NOT NULL,
    data BYTEA NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

-- photo_url becomes a storage key; each status transition gets its own timestamp.
ALTER TABLE visitor_entry RENAME COLUMN photo_url TO photo_key;
ALTER TABLE visitor_entry RENAME COLUMN entry_time TO logged_at;
ALTER TABLE visitor_entry RENAME COLUMN exit_time TO exited_at;
ALTER TABLE visitor_entry ADD COLUMN entered_at TIMESTAMP;

ALTER TABLE visitor_entry
    ALTER COLUMN society_id SET NOT NULL,
    ALTER COLUMN flat_id SET NOT NULL,
    ALTER COLUMN logged_by SET NOT NULL,
    ALTER COLUMN status SET NOT NULL,
    ALTER COLUMN logged_at SET NOT NULL;

-- Newest-first listing per society (the gate log); per-flat status lookups use idx_visitor_entry_flat_status.
CREATE INDEX idx_visitor_entry_society_logged ON visitor_entry(society_id, logged_at DESC);
