-- Maintenance credit and refunds (finance plan, step 3).
--
-- A payment may now be more than the flat owes (society setting acceptAdvancePayments). The part not
-- allocated to any bill is the flat's credit. Credit is never stored as a balance: it is always
--   payment amount - its allocations - its refund allocations (refunds waiting or completed),
-- over the flat's RECORDED payments. When bills are issued, the credit pays them (allocations marked
-- from_credit); a refund pays some of it back.

-- Where the money went in the books (a finance cash/bank ledger). Kept as a plain number: maintenance
-- doesn't know the books; finance checks it when it posts the payment.
ALTER TABLE maintenance_payment
    ADD COLUMN deposit_account_id BIGINT;

-- from_credit: made later, from the payment's unused credit, on applied_on (the new cycle's start).
-- A payment can now reach the same bill twice (once directly, once from credit after a void reopened it),
-- so the one-allocation-per-bill rule goes.
ALTER TABLE maintenance_payment_allocation
    ADD COLUMN from_credit BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN applied_on DATE,
    ADD CHECK (from_credit = (applied_on IS NOT NULL)),
    DROP CONSTRAINT maintenance_payment_allocation_payment_id_bill_id_key;

CREATE INDEX idx_maintenance_payment_allocation_payment ON maintenance_payment_allocation(payment_id);

-- Unused credit paid back to a flat. Above financeApprovalAbove it waits for a second person.
CREATE TABLE maintenance_refund (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    society_id BIGINT NOT NULL REFERENCES society(id),
    flat_id BIGINT NOT NULL REFERENCES flat(id),
    -- RF-000001 … per society.
    refund_number VARCHAR(30) NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL,
    method VARCHAR(20) NOT NULL CHECK (method IN ('CASH','CHEQUE','UPI','BANK_TRANSFER')),
    -- The finance cash/bank ledger it was paid from, if given; checked by finance.
    paid_from_account_id BIGINT,
    reference VARCHAR(100),
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_APPROVAL','COMPLETED','REJECTED','VOID')),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES users(id),
    decided_at TIMESTAMP,
    decided_by BIGINT REFERENCES users(id),
    decision_reason VARCHAR(500),
    voided_at TIMESTAMP,
    voided_by BIGINT REFERENCES users(id),
    void_reason VARCHAR(500),
    UNIQUE (society_id, refund_number)
);

CREATE INDEX idx_maintenance_refund_society ON maintenance_refund(society_id, created_at DESC);
CREATE INDEX idx_maintenance_refund_flat ON maintenance_refund(flat_id);

-- Which payments' credit a refund used, oldest payment first. Counts while the refund waits or is
-- completed; a rejected or void refund gives the credit back.
CREATE TABLE maintenance_refund_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id BIGINT NOT NULL REFERENCES maintenance_refund(id),
    payment_id BIGINT NOT NULL REFERENCES maintenance_payment(id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    UNIQUE (refund_id, payment_id)
);

CREATE INDEX idx_maintenance_refund_allocation_payment ON maintenance_refund_allocation(payment_id);

