-- A complaint's timeline: raised, then every status change, each with an optional note (e.g. how it was
-- fixed, or why it was reopened). Withdrawing a complaint removes its timeline with it.
CREATE TABLE complaint_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL REFERENCES complaint(id) ON DELETE CASCADE,
    -- NULL when the complaint was raised.
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    note TEXT,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_complaint_activity_complaint ON complaint_activity(complaint_id, created_at);
